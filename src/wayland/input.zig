        c_linux.KEY_D => .d,
        c_linux.KEY_E => .e,
        c_linux.KEY_F => .f,
        c_linux.KEY_G => .g,
        c_linux.KEY_H => .h,
        c_linux.KEY_I => .i,
        c_linux.KEY_J => .j,
        c_linux.KEY_K => .k,
        c_linux.KEY_L => .l,
        c_linux.KEY_M => .m,
        c_linux.KEY_N => .n,
        c_linux.KEY_O => .o,
        c_linux.KEY_P => .p,
        c_linux.KEY_Q => .q,
        c_linux.KEY_R => .r,
        c_linux.KEY_S => .s,
        c_linux.KEY_T => .t,
        c_linux.KEY_U => .u,
        c_linux.KEY_V => .v,
        c_linux.KEY_W => .w,
        c_linux.KEY_X => .x,
        c_linux.KEY_Y => .y,
        c_linux.KEY_Z => .z,

        c_linux.KEY_KP0 => .kp_0,
        c_linux.KEY_KP1 => .kp_1,
        c_linux.KEY_KP2 => .kp_2,
        c_linux.KEY_KP3 => .kp_3,
        c_linux.KEY_KP4 => .kp_4,
        c_linux.KEY_KP5 => .kp_5,
