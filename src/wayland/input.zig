        c_linux.KEY_F1 => .f1,
        c_linux.KEY_F2 => .f2,
        c_linux.KEY_F3 => .f3,
        c_linux.KEY_F4 => .f4,
        c_linux.KEY_F5 => .f5,
        c_linux.KEY_F6 => .f6,
        c_linux.KEY_F7 => .f7,
        c_linux.KEY_F8 => .f8,
        c_linux.KEY_F9 => .f9,
        c_linux.KEY_F10 => .f10,
